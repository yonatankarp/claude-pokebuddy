import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { PNG } from 'pngjs'
import { base64Encode, rleEncode } from '../hooks/codec.ts'
import type { Animation, Growth, SpeciesData } from '../hooks/data/types.ts'
import { evolutionsFrom, evolvesFromId, type ChainLink } from './gen1.ts'
import { parseAnim } from './anim.ts'
import { clearFrames, cropAndIndex, cropOffset, iconShinyPalette, indexFrames, packNibbles, shinyPalette } from './pack.ts'

const RAW = new URL('./raw/', import.meta.url)
const json = async (p: string) => JSON.parse(await readFile(new URL(p, RAW), 'utf8'))
const png = async (p: string) => PNG.sync.read(await readFile(new URL(p, RAW)))

const GROWTH: Record<string, Growth> = {
  fast: 'fast', medium: 'medium-fast', 'medium-slow': 'medium-slow', slow: 'slow',
}

const clean = (s: string) => s.replace(/\u00ad[\n\f]?/g, '').replace(/[\f\n]+/g, ' ').replace(/\s+/g, ' ').trim()

const out: SpeciesData[] = []
const animations: Animation[] = []
for (let id = 1; id <= 151; id++) {
  const species = await json(`species/${id}.json`)
  const pokemon = await json(`pokemon/${id}.json`)
  const chainId = Number(String(species.evolution_chain.url).split('/').filter(Boolean).pop())
  const chain: { chain: ChainLink } = await json(`chains/${chainId}.json`)
  const normal = await png(`sprites/${id}.png`)
  const shiny = await png(`sprites/shiny/${id}.png`)
  const indexed = cropAndIndex(new Uint8Array(normal.data), normal.width, normal.height)
  const off = cropOffset(new Uint8Array(normal.data), normal.width, normal.height)
  const iconPng = await png(`icons/${id}.png`)
  const icon = cropAndIndex(new Uint8Array(iconPng.data), iconPng.width, iconPng.height)
  const front = await png(`crystal/${id}/front.png`)
  const frames = indexFrames(clearFrames(new Uint8Array(front.data), front.width, front.height, new Uint8Array(normal.data), normal.width), front.width, indexed.palette)
  const anim = {
    intro: parseAnim(await readFile(new URL(`crystal/${id}/anim.asm`, RAW), 'utf8')),
    idle: parseAnim(await readFile(new URL(`crystal/${id}/anim_idle.asm`, RAW), 'utf8')),
  }
  const missing = [...anim.intro, ...anim.idle].find(s => s.frame >= frames.frames.length)
  if (missing) throw new Error(`#${id}: animation shows frame ${missing.frame} of ${frames.frames.length}`)
  const crystalShiny = shinyPalette(indexed, new Uint8Array(shiny.data), shiny.width, shiny.height, off.x, off.y)
  const flavour = species.flavor_text_entries.find((f: any) => f.language.name === 'en' && f.version.name === 'crystal')
    ?? species.flavor_text_entries.find((f: any) => f.language.name === 'en')
  const growth = GROWTH[species.growth_rate.name]
  if (!growth) throw new Error(`#${id}: unexpected growth rate ${species.growth_rate.name}`)
  out.push({
    id,
    name: species.names.find((n: any) => n.language.name === 'en').name.toUpperCase(),
    // Gen 1 typing: the earliest past_types entry wins (Clefairy is Normal, Magnemite is pure Electric).
    types: (pokemon.past_types?.[0]?.types ?? pokemon.types).map((t: any) => t.type.name),
    height: pokemon.height,
    weight: pokemon.weight,
    dex: clean(flavour.flavor_text),
    growth,
    evolvesFrom: evolvesFromId(species.evolves_from_species?.url ?? null),
    evolutions: evolutionsFrom(chain.chain, id),
    sprite: {
      w: indexed.w, h: indexed.h,
      px: base64Encode(packNibbles(indexed.indexes)),
      palette: indexed.palette,
      shiny: crystalShiny,
    },
    icon: {
      w: icon.w, h: icon.h,
      px: base64Encode(packNibbles(icon.indexes)),
      palette: icon.palette,
      shiny: iconShinyPalette(icon.palette, indexed.palette, crystalShiny),
    },
  })
  animations.push({ frames: { w: frames.w, h: frames.h, px: frames.frames.map(f => base64Encode(rleEncode(f))) }, anim })
}

// The plugin loader does not read a module over 1 MiB; check both before writing either.
const HEADER = `// Generated by scripts/bake.ts from PokeAPI data and the pret/pokecrystal disassembly. Do not edit.\n`
const files = {
  'pokedex.generated.ts': HEADER + `import type { SpeciesData } from './types'\n\nexport const POKEDEX: readonly SpeciesData[] = ${JSON.stringify(out)}\n`,
  'animation.generated.ts': HEADER + `import type { Animation } from './types'\n\nexport const ANIMATIONS: readonly Animation[] = ${JSON.stringify(animations)}\n`,
}
const LIMIT = 1_000_000
for (const [name, body] of Object.entries(files)) {
  if (Buffer.byteLength(body) > LIMIT) throw new Error(`${name} would be ${Buffer.byteLength(body)} bytes, over ${LIMIT}`)
}
for (const [name, body] of Object.entries(files)) await writeFile(new URL(`../hooks/data/${name}`, import.meta.url), body)

await mkdir(new URL('./golden/', import.meta.url), { recursive: true })
for (const id of [25, 151, 130]) {
  const s = out[id - 1]!
  await writeFile(new URL(`./golden/${id}.json`, import.meta.url), JSON.stringify(s.sprite, null, 2) + '\n')
}
console.log(`baked ${out.length} species: ${Object.entries(files).map(([n, b]) => `${n} ${(Buffer.byteLength(b) / 1024).toFixed(0)} KB`).join(', ')}`)
