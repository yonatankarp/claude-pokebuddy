import { readFile, writeFile } from 'node:fs/promises'
import { PNG } from 'pngjs'
import { base64Encode } from '../plugin/hooks/codec.ts'
import type { Growth, Species } from '../plugin/hooks/data/types.ts'
import { evolutionsFrom, evolvesFromId, type ChainLink } from './gen1.ts'
import { verifyRaw } from './sources.ts'
import { cropAndIndex, cropOffset, iconShinyPalette, packNibbles, shinyPalette } from './pack.ts'
import { artists, bakeIdle, idleAnim, idleTiming } from './pmd.ts'

const RAW = new URL('./raw/', import.meta.url)
const json = async (p: string) => JSON.parse(await readFile(new URL(p, RAW), 'utf8'))
const png = async (p: string) => PNG.sync.read(await readFile(new URL(p, RAW)))

const GROWTH: Record<string, Growth> = {
  fast: 'fast', medium: 'medium-fast', 'medium-slow': 'medium-slow', slow: 'slow',
}

const clean = (s: string) => s.replace(/\u00ad[\n\f]?/g, '').replace(/[\f\n]+/g, ' ').replace(/\s+/g, ' ').trim()

await verifyRaw()

const out: Species[] = []
const names = await readFile(new URL('pmd/credit_names.txt', RAW), 'utf8')
const credits: string[] = []
for (let id = 1; id <= 151; id++) {
  const species = await json(`species/${id}.json`)
  const pokemon = await json(`pokemon/${id}.json`)
  const chainId = Number(String(species.evolution_chain.url).split('/').filter(Boolean).pop())
  const chain: { chain: ChainLink } = await json(`chains/${chainId}.json`)
  const normal = await png(`sprites/${id}.png`)
  const shiny = await png(`sprites/shiny/${id}.png`)
  const indexed = cropAndIndex(new Uint8Array(normal.data), normal.width, normal.height)
  const off = cropOffset(new Uint8Array(normal.data), normal.width, normal.height)
  const iconPng = await png(`icons/${id}.png`)
  const icon = cropAndIndex(new Uint8Array(iconPng.data), iconPng.width, iconPng.height)
  const crystalShiny = shinyPalette(indexed, new Uint8Array(shiny.data), shiny.width, shiny.height, off.x, off.y)
  const pmdXml = await readFile(new URL(`pmd/${id}.xml`, RAW), 'utf8')
  const sheet = await png(`pmd/${id}.png`), shinySheet = await png(`pmd/shiny/${id}.png`)
  const idle = bakeIdle({ data: new Uint8Array(sheet.data), width: sheet.width }, { data: new Uint8Array(shinySheet.data), width: shinySheet.width }, idleTiming(pmdXml))
  const anim = idleAnim(pmdXml)
  const drew = artists(await readFile(new URL(`pmd/${id}.credits`, RAW), 'utf8'), names, anim)
  const recoloured = artists(await readFile(new URL(`pmd/shiny/${id}.credits`, RAW), 'utf8'), names, anim)
  const flavour = species.flavor_text_entries.find((f: any) => f.language.name === 'en' && f.version.name === 'crystal')
    ?? species.flavor_text_entries.find((f: any) => f.language.name === 'en')
  const growth = GROWTH[species.growth_rate.name]
  if (!growth) throw new Error(`#${id}: unexpected growth rate ${species.growth_rate.name}`)
  out.push({
    id,
    name: species.names.find((n: any) => n.language.name === 'en').name.toUpperCase(),
    // Gen 1 typing: the earliest past_types entry wins (Clefairy is Normal, Magnemite is pure Electric).
    types: (pokemon.past_types?.[0]?.types ?? pokemon.types).map((t: any) => t.type.name),
    height: pokemon.height,
    weight: pokemon.weight,
    dex: clean(flavour.flavor_text),
    growth,
    evolvesFrom: evolvesFromId(species.evolves_from_species?.url ?? null),
    evolutions: evolutionsFrom(chain.chain, id),
    icon: {
      w: icon.w, h: icon.h,
      px: base64Encode(packNibbles(icon.indexes)),
      palette: icon.palette,
      shiny: iconShinyPalette(icon.palette, indexed.palette, crystalShiny),
    },
    idle,
  })
  credits.push(`| ${String(id).padStart(3, '0')} | ${out[out.length - 1]!.name} | ${drew.join(', ') || 'unknown'} | ${recoloured.join(', ') || 'unknown'} |`)
}

const body = `// Generated by scripts/bake.ts from PokeAPI data. Do not edit.\n` +
  `import type { Species } from './types'\n\n` +
  `export const POKEDEX: readonly Species[] = ${JSON.stringify(out)}\n`
// The plugin loader does not read a module over 1 MiB.
const LIMIT = 1_000_000
if (Buffer.byteLength(body) > LIMIT) throw new Error(`pokedex.generated.ts would be ${Buffer.byteLength(body)} bytes, over ${LIMIT}`)
await writeFile(new URL('../plugin/hooks/data/pokedex.generated.ts', import.meta.url), body)

// The idle sprites are CC BY-NC 4.0 and ask for credit, so the artists ship with the plugin.
await writeFile(new URL('../plugin/SPRITE-CREDITS.md', import.meta.url), [
  '# Idle sprite credits', '',
  'The app\'s idle animations are the Pokémon Mystery Dungeon sprites from [PMDCollab SpriteCollab](https://github.com/PMDCollab/SpriteCollab),',
  'shared under [CC BY-NC 4.0](https://creativecommons.org/licenses/by-nc/4.0/). pokebuddy uses the idle facing the viewer and its shiny recolour,',
  'cropped and reduced to one palette. Artists as SpriteCollab credits them, by name or, where it lists none, by id; CHUNSOFT is Spike Chunsoft\'s original art.', '',
  '| No. | Pokémon | Idle | Shiny |', '| --- | --- | --- | --- |', ...credits, '',
].join('\n'))

console.log(`baked ${out.length} species, ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`)
